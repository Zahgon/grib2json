/// `ParameterTable.getParameterName(discipline, category, number)`.
pub fn parameter_name(discipline: i32, category: i32, number: i32) -> String {
    match parameter(discipline, category, number) {
        Some((name, _)) => name.to_string(),
        None => format!("UnknownParameter_D{discipline}_C{category}_{number}"),
    }
}

/// `ParameterTable.getParameterUnit(discipline, category, number)`.
pub fn parameter_unit(discipline: i32, category: i32, number: i32) -> String {
    match parameter(discipline, category, number) {
        Some((_, unit)) => unit.to_string(),
        None => UNKNOWN.to_string(),
    }
}
