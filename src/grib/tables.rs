//! Port of the netCDF-Java code tables grib2json reads through:
//! `ucar.grib.grib2.Grib2Tables`, `ucar.grib.grib2.ParameterTable`,
//! `ucar.grib.grib1.Grib1Tables` and the `*Name()` accessors on the indicator
//! and identification sections.
//!
//! **These entries were extracted from the Java classes, not transcribed from
//! the WMO manual.** A probe on the classpath of the Java build called each
//! accessor over its code range and printed what came back; this file is that
//! output. That matters because netCDF-Java's spellings are its own -- it says
//! `"Rotated_Latitude_Longitude"` where the manual says "rotated latitude
//! longitude", and `"Earth represent by WGS84"` with the grammar slip intact.
//! Any of those differences would show up in a `--names` header.
//!
//! Each fallback is netCDF-Java's own, including the ones that embed the code:
//! `"Unknown projection42"`, `"Unknown=99"`, `"UnknownParameter_D0_C2_99"`.

/// netCDF-Java's plain fallback, used by the tables that have no formatted one.
const UNKNOWN: &str = "Unknown";

/// `Grib2IndicatorSection.getDisciplineName()`.
///
/// Not the same table as [`parameter_table_discipline_name`], despite the name.
/// The indicator section spells discipline 0 `"Meteorological products"` with a
/// space; `ParameterTable` spells the same code `"Meteorological_products"` with
/// an underscore. `GribRecordWriter.writeIndicator` reads the first,
/// `OscarRecordWriter.writeIndicator` reads the second, so both are kept and
/// neither is allowed to stand in for the other.
pub fn discipline_name(discipline: i32) -> String {
    match discipline {
        0 => "Meteorological products",
        1 => "Hydrological products",
        2 => "Land surface products",
        3 => "Space products",
        10 => "Oceanographic products",
        _ => UNKNOWN,
    }
    .to_string()
}

